export interface TemplateFiles {
  [path: string]: string;
}

/** Files generated for a new community plugin package. */
export function pluginTemplates(name: string): TemplateFiles {
  const packageName = `rnctl-plugin-${name}`;
  return {
    'package.json': [
      '{',
      `  "name": "${packageName}",`,
      '  "version": "0.1.0",',
      `  "description": "rnctl plugin: ${name}",`,
      '  "type": "module",',
      '  "main": "./dist/index.js",',
      '  "types": "./dist/index.d.ts",',
      '  "exports": { ".": { "types": "./dist/index.d.ts", "import": "./dist/index.js" } },',
      '  "files": ["dist"],',
      '  "license": "MIT",',
      '  "publishConfig": { "access": "public" },',
      '  "scripts": {',
      '    "build": "tsup src/index.ts --format esm --dts --clean",',
      '    "typecheck": "tsc --noEmit",',
      '    "test": "vitest run --passWithNoTests",',
      '    "clean": "rm -rf dist"',
      '  },',
      '  "peerDependencies": { "@rnctl/sdk": ">=0.1.0" },',
      '  "devDependencies": { "@rnctl/sdk": ">=0.1.0", "tsup": "latest", "typescript": "latest", "vitest": "latest" }',
      '}',
      '',
    ].join('\n'),
    'tsconfig.json': [
      '{',
      '  "compilerOptions": {',
      '    "target": "ES2022",',
      '    "module": "NodeNext",',
      '    "moduleResolution": "NodeNext",',
      '    "strict": true,',
      '    "esModuleInterop": true,',
      '    "skipLibCheck": true,',
      '    "types": ["node"],',
      '    "outDir": "dist",',
      '    "rootDir": "src"',
      '  },',
      '  "include": ["src/**/*.ts"]',
      '}',
      '',
    ].join('\n'),
    'src/index.ts': [
      `import { definePlugin, z } from '@rnctl/sdk';`,
      '',
      'export default definePlugin({',
      `  name: '${packageName}',`,
      "  version: '0.1.0',",
      `  description: 'rnctl plugin: ${name}',`,
      '  async setup(ctx) {',
      `    ctx.registerRpc('${name}.ping', {`,
      '      inputSchema: z.object({ echo: z.string() }),',
      '      handler: async ({ echo }) => ({ reply: echo }),',
      '    });',
      `    ctx.logger.info('${packageName} ready');`,
      '  },',
      '});',
      '',
    ].join('\n'),
    'src/index.test.ts': [
      `import { definePlugin } from '@rnctl/sdk';`,
      `import { describe, expect, it } from 'vitest';`,
      `import plugin from './index.js';`,
      '',
      `describe('${name} plugin', () => {`,
      "  it('exports a plugin definition', () => {",
      '    expect(plugin.name).toBe(\'' + packageName + '\');',
      '    expect(typeof plugin.setup).toBe(\'function\');',
      '  });',
      '});',
      '',
    ].join('\n'),
    'README.md': [
      `# ${packageName}`,
      '',
      `A community plugin for [rnctl](https://github.com/bittu/rnctl).`,
      '',
      '## Development',
      '',
      '```sh',
      'pnpm install',
      'pnpm typecheck',
      'pnpm test',
      'pnpm build',
      '```',
      '',
      '## Discovery',
      '',
      'rnctl auto-loads packages named `rnctl-plugin-*` from a project\'s `node_modules`.',
      'The default export must be a `definePlugin(...)` object with `name` and `setup`.',
      '',
    ].join('\n'),
    '.gitignore': ['node_modules/', 'dist/', ''].join('\n'),
  };
}
